-- =====================================================================
-- STEP 14  Cleanup (run as ACCOUNTADMIN, in this order)
-- =====================================================================
USE ROLE ACCOUNTADMIN;

-- 1. Detach policies (skip the first line if you skipped Step 5.3)
ALTER ACCOUNT UNSET DATA MOVEMENT POLICY;
ALTER TAG DMP_LAB_DB.GOVERNANCE.MOVEMENT_TIER
  UNSET DATA MOVEMENT POLICY DMP_LAB_DB.GOVERNANCE.P_RESTRICTED_TABLE;
ALTER TAG DMP_LAB_DB.GOVERNANCE.PII_CRITICAL
  UNSET DATA MOVEMENT POLICY DMP_LAB_DB.GOVERNANCE.P_PII_CRITICAL_COLUMN;

-- 2. Drop policies
USE SCHEMA DMP_LAB_DB.GOVERNANCE;
DROP DATA MOVEMENT POLICY IF EXISTS P_RESTRICTED_TABLE;
DROP DATA MOVEMENT POLICY IF EXISTS P_PII_CRITICAL_COLUMN;
DROP DATA MOVEMENT POLICY IF EXISTS P_ACCOUNT_BASELINE;

-- 3. Drop rules
DROP DATA MOVEMENT RULE IF EXISTS R_UI_VIEW_ENFORCE;
DROP DATA MOVEMENT RULE IF EXISTS R_UI_VIEW_ALERT;
DROP DATA MOVEMENT RULE IF EXISTS R_UI_DOWNLOAD_ENFORCE;
DROP DATA MOVEMENT RULE IF EXISTS R_STAGE_ENFORCE;
DROP DATA MOVEMENT RULE IF EXISTS R_STAGE_ALERT;
DROP DATA MOVEMENT RULE IF EXISTS R_FETCH_ENFORCE;
DROP DATA MOVEMENT RULE IF EXISTS R_FETCH_ALERT;
DROP DATA MOVEMENT RULE IF EXISTS R_AGENT_ENFORCE;
DROP DATA MOVEMENT RULE IF EXISTS R_AGENT_ALERT;
DROP DATA MOVEMENT RULE IF EXISTS C_UI_VIEW_ENFORCE;
DROP DATA MOVEMENT RULE IF EXISTS C_UI_DOWNLOAD_ENFORCE;
DROP DATA MOVEMENT RULE IF EXISTS C_STAGE_ENFORCE;
DROP DATA MOVEMENT RULE IF EXISTS C_FETCH_ENFORCE;
DROP DATA MOVEMENT RULE IF EXISTS C_AGENT_ENFORCE;
DROP DATA MOVEMENT RULE IF EXISTS A_FETCH_BASELINE;

-- 4. Drop data, tags, stage, warehouse and database
DROP DATABASE IF EXISTS DMP_LAB_DB;
DROP WAREHOUSE IF EXISTS DMP_LAB_WH;

-- 5. Drop roles
USE ROLE USERADMIN;
DROP ROLE IF EXISTS DMP_LAB_ANALYST;
DROP ROLE IF EXISTS DMP_LAB_STEWARD;

