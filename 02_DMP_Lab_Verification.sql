-- =====================================================================
-- STEP 13.1  Blocked statements from query history (admin worksheet)
-- =====================================================================
USE ROLE ACCOUNTADMIN;
USE WAREHOUSE DMP_LAB_WH;

SELECT QUERY_ID, USER_NAME, ROLE_NAME, EXECUTION_STATUS,
       LEFT(ERROR_MESSAGE, 120) AS ERROR_MESSAGE, START_TIME
FROM TABLE(DMP_LAB_DB.INFORMATION_SCHEMA.QUERY_HISTORY(RESULT_LIMIT => 500))
WHERE ROLE_NAME IN ('DMP_LAB_ANALYST', 'DMP_LAB_STEWARD')
  AND EXECUTION_STATUS LIKE 'FAILED%'
  AND ERROR_MESSAGE ILIKE '%data movement policy%'
ORDER BY START_TIME DESC
LIMIT 50;

-- =====================================================================
-- STEP 13.2  Violations recorded in ACCOUNT_USAGE (latency up to ~3 hours)
-- =====================================================================
DESCRIBE VIEW SNOWFLAKE.ACCOUNT_USAGE.DATA_MOVEMENT_VIOLATIONS;

-- One row per violation, labelled BLOCKED or ALERT. Export events can arrive
-- without a user or timestamp, so the join to query history fills them in.
USE ROLE ACCOUNTADMIN;
USE WAREHOUSE DMP_LAB_WH;
SELECT V.QUERY_ID,
       V.MOVEMENT_TYPE,
       IFF(V.ENFORCED_POLICY IS NULL OR V.ENFORCED_POLICY = '',
           'ALERT', 'BLOCKED')                       AS OUTCOME,
       COALESCE(NULLIF(V.USER_NAME, ''), Q.USER_NAME) AS USER_NAME,
       COALESCE(V.TIMESTAMP, Q.START_TIME)            AS EVENT_TIME
FROM SNOWFLAKE.ACCOUNT_USAGE.DATA_MOVEMENT_VIOLATIONS V
LEFT JOIN SNOWFLAKE.ACCOUNT_USAGE.QUERY_HISTORY Q
       ON Q.QUERY_ID = V.QUERY_ID
--Where   EVENT_TIME::DATE = CURRENT_DATE()     
ORDER BY EVENT_TIME DESC NULLS LAST
LIMIT 50;